#!/usr/bin/env node
/**
 * Generates `frontend/src/app/games/registry.generated.ts`, the list of game UIs the Angular app
 * can load. Every folder `games/<id>/` that contains `frontend/index.ts` becomes a lazily loaded
 * chunk, so adding a game never requires touching platform code.
 *
 * Runs automatically before `npm start` / `npm run build` in `frontend/`.
 *
 * Environment:
 *   FF_GAMES=a,b   only bundle the listed games (mirrors `-PffGames=a,b` for Gradle)
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const gamesDir = path.join(root, 'games');
const target = path.join(root, 'frontend', 'src', 'app', 'games', 'registry.generated.ts');
const ID_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;

const filter = (process.env.FF_GAMES ?? '')
  .split(',')
  .map((id) => id.trim())
  .filter(Boolean);

const ids = readdirSync(gamesDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && !entry.name.startsWith('_') && !entry.name.startsWith('.'))
  .map((entry) => entry.name)
  .filter((id) => existsSync(path.join(gamesDir, id, 'frontend', 'index.ts')))
  .filter((id) => filter.length === 0 || filter.includes(id))
  .sort();

for (const id of ids) {
  if (!ID_PATTERN.test(id)) {
    console.error(`games/${id}: folder names must be kebab-case (they are the game id).`);
    process.exit(1);
  }
}

const entries = ids.map((id) => `  '${id}': () => import('@games/${id}/frontend').then((m) => m.default),`);
const content = `// AUTO-GENERATED by scripts/generate-game-registry.mjs — do not edit by hand.
// One lazy chunk per games/<id>/frontend/index.ts. Regenerate with \`npm run generate:games\`.
import type { GameUiLoader } from '@ff/sdk';

export const GAME_UI_LOADERS: Readonly<Record<string, GameUiLoader>> = {
${entries.join('\n')}
};
`;

// Only write when something changed, so `ng serve` doesn't rebuild for nothing.
const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
if (current !== content) {
  writeFileSync(target, content);
  console.log(`Game registry updated: ${ids.join(', ') || '(no games)'}`);
}
if (filter.length > 0) {
  console.warn('FF_GAMES is set: run `npm run generate:games` before committing to list every game again.');
}
